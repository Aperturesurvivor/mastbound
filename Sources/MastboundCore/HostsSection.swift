import Foundation

/// Renders and reads the one marked section of `/etc/hosts` that Mastbound
/// owns. Lines outside the markers are never changed.
public enum HostsSection {
    public static let beginMarker = "# BEGIN MASTBOUND — MANAGED BLOCK"
    public static let endMarker = "# END MASTBOUND — MANAGED BLOCK"
    public static let maximumDomains = 250_000

    /// Returns `existing` with the managed section replaced by `blockedDomains`
    /// and `redirects`. Both empty removes the section. A redirect for a
    /// blocked name is left out: the block wins.
    public static func render(existing: String, blockedDomains: [String], redirects: [HostsRedirect] = []) throws -> String {
        let domains = try DomainValidator.normalize(blockedDomains, maximumCount: maximumDomains)
        let blocked = Set(domains)
        var seen = Set<String>()
        let redirectRows = try redirects.filter { redirect in
            let name = redirect.name.lowercased()
            try DomainValidator.validate(name)
            guard isAddress(redirect.ipv4, family: AF_INET), redirect.ipv6.map({ isAddress($0, family: AF_INET6) }) ?? true else {
                throw MastboundError.invalidList("A SafeSearch address is not valid.")
            }
            return !blocked.contains(name) && seen.insert(name).inserted
        }
        var lines = splitLines(existing)
        if let range = try managedRange(in: lines) {
            lines.removeSubrange(range)
            while lines.last == "" { lines.removeLast() }
        }
        if !domains.isEmpty || !redirectRows.isEmpty {
            if !lines.isEmpty { lines.append("") }
            lines.append(beginMarker)
            lines.append("# Generated by Mastbound. Do not edit this section by hand.")
            for domain in domains {
                lines.append("0.0.0.0\t\(domain)")
                lines.append("::\t\(domain)")
            }
            if !redirectRows.isEmpty { lines.append("# Forced SafeSearch") }
            for redirect in redirectRows {
                let name = redirect.name.lowercased()
                lines.append("\(redirect.ipv4)\t\(name)")
                lines.append("\(redirect.ipv6 ?? "::")\t\(name)")
            }
            lines.append(endMarker)
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// The domains currently in the managed section, or `[]` if there is none.
    public static func managedDomains(in contents: String) throws -> [String] {
        let lines = splitLines(contents)
        guard let range = try managedRange(in: lines) else { return [] }
        let body = lines[(range.lowerBound + 1)..<range.upperBound]
        let domains = body.compactMap { line -> String? in
            let fields = line.split(whereSeparator: { $0 == " " || $0 == "\t" })
            guard fields.count == 2, fields[0] == "0.0.0.0" else { return nil }
            return String(fields[1])
        }
        return try DomainValidator.normalize(domains, maximumCount: maximumDomains)
    }

    private static func isAddress(_ text: String, family: Int32) -> Bool {
        var buffer = [UInt8](repeating: 0, count: 16)
        return inet_pton(family, text, &buffer) == 1
    }

    private static func splitLines(_ text: String) -> [String] {
        var lines = text.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        if lines.last == "" { lines.removeLast() }
        return lines
    }

    /// Closed range from begin marker to end marker. Throws on any marker
    /// problem so that a damaged file is never edited.
    private static func managedRange(in lines: [String]) throws -> ClosedRange<Int>? {
        let begins = lines.indices.filter { lines[$0] == beginMarker }
        let ends = lines.indices.filter { lines[$0] == endMarker }
        guard begins.count == ends.count, begins.count <= 1 else {
            throw MastboundError.malformedHostsSection(
                "The Mastbound hosts section has missing or duplicate markers."
            )
        }
        guard let begin = begins.first, let end = ends.first else { return nil }
        guard begin < end else {
            throw MastboundError.malformedHostsSection("The Mastbound hosts markers are out of order.")
        }
        return begin...end
    }
}
