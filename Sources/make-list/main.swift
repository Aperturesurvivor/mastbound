import Foundation
import MastboundCore

// Developer tool. Usage:
//   make-list <output-list> <output-swift> <source-hosts-file>...
// Merges upstream hosts files into the canonical list format and writes the
// pinned hash into a Swift source file. Run through script/make-list.sh.

let arguments = Array(CommandLine.arguments.dropFirst())
guard arguments.count >= 3 else {
    FileHandle.standardError.write(Data("usage: make-list <output-list> <output-swift> <source>...\n".utf8))
    exit(2)
}
do {
    var domains = Set<String>()
    for path in arguments.dropFirst(2) {
        let found = try Blocklist.domainsFromHostsSource(Data(contentsOf: URL(fileURLWithPath: path)))
        print("\(found.count)\t\(path)")
        domains.formUnion(found)
    }
    let data = try Blocklist.serialize(Array(domains))
    let list = try Blocklist.parse(data)
    try data.write(to: URL(fileURLWithPath: arguments[0]))
    let swift = """
    // Generated by script/make-list.sh. Do not edit by hand.

    /// Identity of the list in `Resources/adult-domains.txt`.
    public enum BundledList {
        public static let sha256 = "\(list.sha256)"
        public static let domainCount = \(list.domains.count)
    }

    """
    try Data(swift.utf8).write(to: URL(fileURLWithPath: arguments[1]))
    print("total\t\(list.domains.count)\nsha256\t\(list.sha256)")
} catch {
    FileHandle.standardError.write(Data("make-list: \(error.localizedDescription)\n".utf8))
    exit(1)
}
