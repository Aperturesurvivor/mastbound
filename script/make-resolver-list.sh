#!/usr/bin/env bash
# Rebuilds Resources/resolver-domains.txt from Resources/adult-domains.txt and a
# pinned Tranco list. Usage: script/make-resolver-list.sh LIST_ID
# Example: script/make-resolver-list.sh V38GN
# The file holds the root domains of the blocklist that appear in the Tranco
# top 1M, best rank first. A root domain is a list domain with no parent
# domain in the list. Its rank is the best Tranco rank of the root itself or
# of any list domain under it.
set -euo pipefail

if [[ $# -ne 1 || ! "$1" =~ ^[A-Za-z0-9]{4,8}$ ]]; then
  echo "usage: $0 TRANCO_LIST_ID" >&2
  exit 2
fi
LIST_ID="$1"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK_DIR="$(/usr/bin/mktemp -d)"
trap '/bin/rm -rf "$WORK_DIR"' EXIT

# The downloaded data goes in its own folder. The script goes in another one.
/bin/mkdir "$WORK_DIR/data" "$WORK_DIR/code"

/usr/bin/curl --fail --silent --show-error --proto '=https' --max-filesize 1048576 \
  --output "$WORK_DIR/data/meta.json" "https://tranco-list.eu/api/lists/id/$LIST_ID"
/usr/bin/curl --fail --silent --show-error --location --proto '=https' --max-filesize 104857600 \
  --output "$WORK_DIR/data/top-1m.csv" "https://tranco-list.eu/download/$LIST_ID/1000000"

cat > "$WORK_DIR/code/build.py" <<'PY'
import csv
import json
import sys

meta_path, tranco_path, list_path, out_path, list_id = sys.argv[1:6]

with open(meta_path, encoding="utf-8") as f:
    meta = json.load(f)
if meta.get("list_id") != list_id or not meta.get("available") or meta.get("failed"):
    sys.exit("Tranco list %s is not available" % list_id)
list_date = meta["created_on"][:10]

domains = set()
with open(list_path, encoding="utf-8") as f:
    for line in f:
        line = line.strip().lower()
        if line and not line.startswith("#"):
            domains.add(line)

tranco = {}
with open(tranco_path, encoding="utf-8", newline="") as f:
    for row in csv.reader(f):
        if len(row) == 2 and row[0].isdigit():
            tranco[row[1].strip().lower()] = int(row[0])
if len(tranco) < 900000:
    sys.exit("Tranco list is too short: %d rows" % len(tranco))

def has_parent_in_list(domain):
    labels = domain.split(".")
    return any(".".join(labels[i:]) in domains for i in range(1, len(labels)))

roots = {d for d in domains if not has_parent_in_list(d)}

best = {}
for d in domains:
    rank = tranco.get(d)
    if rank is None:
        continue
    labels = d.split(".")
    for i in range(len(labels)):
        candidate = ".".join(labels[i:])
        if candidate in roots:
            if candidate not in best or rank < best[candidate]:
                best[candidate] = rank
            break

ranked = sorted(best, key=lambda d: (best[d], d))
with open(out_path, "w", encoding="utf-8") as f:
    f.write("# Tranco list %s (%s)\n" % (list_id, list_date))
    f.write("# Source: https://tranco-list.eu/list/%s/1000000\n" % list_id)
    f.write("# Count: %d\n" % len(ranked))
    f.write("# Generated by script/make-resolver-list.sh\n")
    for d in ranked:
        f.write(d + "\n")
print("roots=%d ranked=%d" % (len(roots), len(ranked)), file=sys.stderr)
PY

cd "$ROOT_DIR"
/usr/bin/python3 -I "$WORK_DIR/code/build.py" "$WORK_DIR/data/meta.json" "$WORK_DIR/data/top-1m.csv" \
  Resources/adult-domains.txt Resources/resolver-domains.txt "$LIST_ID"

# The daemon reads the ranking from a generated Swift file, so it needs no
# extra installed file.
/usr/bin/python3 -I - Resources/resolver-domains.txt Sources/MastboundCore/ResolverRanking.swift <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
lines = [l.strip() for l in open(src, encoding="utf-8") if l.strip() and not l.startswith("#")]
allowed = set("abcdefghijklmnopqrstuvwxyz0123456789-.")
assert all(set(d) <= allowed for d in lines), "unexpected character in a domain"
with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated from Resources/resolver-domains.txt by script/make-resolver-list.sh.\n")
    f.write("// Do not edit. Ranked by the Tranco list (see ATTRIBUTIONS.md), best first.\n\n")
    f.write("/// Listed domains ordered by popularity. See `ResolverFiles`.\n")
    f.write("public enum ResolverRanking {\n")
    f.write('    public static let domains: [String] = text.split(separator: "\\n").map(String.init)\n\n')
    f.write('    private static let text = """\n')
    f.write("\n".join(lines) + "\n")
    f.write('"""\n}\n')
PY
