#!/usr/bin/env bash
# Downloads Google's list of search domains and writes
# Resources/google-domains.txt and Sources/MastboundCore/GoogleDomains.swift.
# Run before a release; review the diff.
set -euo pipefail
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"
WORK="$(mktemp -d)"
trap '/bin/rm -rf "$WORK"' EXIT
/usr/bin/curl -fsSL https://www.google.com/supported_domains -o "$WORK/raw.txt"
/usr/bin/sed 's/^\.//' "$WORK/raw.txt" | /usr/bin/grep -E '^google\.[a-z]{2,}(\.[a-z]{2,})?$' | /usr/bin/sort -u > "$WORK/domains.txt"
count=$(/usr/bin/wc -l < "$WORK/domains.txt" | tr -d ' ')
[[ "$count" -ge 150 ]] || { echo "only $count domains; refusing" >&2; exit 1; }
{
  echo "# Google search domains for forced SafeSearch."
  echo "# Source: https://www.google.com/supported_domains ($(date +%F)). Made by script/make-safesearch-list.sh."
  /bin/cat "$WORK/domains.txt"
} > Resources/google-domains.txt
{
  echo "// Generated by script/make-safesearch-list.sh from Resources/google-domains.txt. Do not edit."
  echo "enum GoogleDomains {"
  echo "    static let all: [String] = ["
  /usr/bin/sed 's/.*/        "&",/' "$WORK/domains.txt"
  echo "    ]"
  echo "}"
} > Sources/MastboundCore/GoogleDomains.swift
echo "wrote $count Google domains"
